<?php

declare(strict_types=1);

namespace Jul6Art\AuthBundle\DependencyInjection;

use Jul6Art\AuthBundle\Entity\User;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

/**
 * Class Configuration.
 */
class Configuration implements ConfigurationInterface
{
    #[\Override]
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('auth');
        $treeBuilder->getRootNode()
            ->children()
                ->booleanNode('enabled')
                    ->info('Exposed as the "auth.enabled" container parameter.')
                    ->defaultTrue()
                ->end()
                ->arrayNode('sign_in_throttling')
                    ->info('A login limiter that counts the sign-in requests only: name "auth.sign_in_throttling.limiter" in the "login_throttling.limiter" of a firewall that also reads a token. Off by default; needs symfony/rate-limiter.')
                    ->canBeEnabled()
                    ->validate()
                        ->ifTrue(static fn (array $value): bool => true === $value['enabled'] && [] === $value['paths'])
                        ->thenInvalid('auth.sign_in_throttling needs at least one path: it would count nothing.')
                    ->end()
                    ->children()
                        ->arrayNode('paths')
                            ->info('The path prefixes where a request is a sign-in attempt, e.g. "/api/auth/" and "/login". Any other request of the firewall is neither counted nor refused.')
                            ->scalarPrototype()->cannotBeEmpty()->end()
                        ->end()
                        ->integerNode('max_attempts')
                            ->info('Failed attempts per identifier and IP within the interval; the IP itself gets five times as many, every identifier together.')
                            ->defaultValue(5)
                            ->min(1)
                        ->end()
                        ->scalarNode('interval')
                            ->info('The window the attempts are counted over.')
                            ->defaultValue('1 minute')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('cache_pool')
                            ->info('The cache pool of the counters. Null: a filesystem pool of the bundle ("auth.sign_in_throttling.cache"). Name your own to clear it between tests — never an array pool, which forgets at the end of each request.')
                            ->defaultNull()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('api_failures')
                    ->info('One JSON answer for every failed authentication of the API firewalls: a uniform 401 that never tells whether an account exists or why a token failed, and a 429 with Retry-After when the login limiter refuses. Off by default; needs symfony/security-bundle.')
                    ->canBeEnabled()
                    ->children()
                        ->arrayNode('firewalls')
                            ->info('The firewalls whose clients read JSON. Never a form login: it redirects and flashes its own message.')
                            ->defaultValue(['api'])
                            ->requiresAtLeastOneElement()
                            ->scalarPrototype()->cannotBeEmpty()->end()
                        ->end()
                        ->scalarNode('invalid_credentials_code')
                            ->info('The "errorCode" of a 401: one value for a wrong password, an unknown account, a disabled one, a bad token.')
                            ->defaultValue('INVALID_CREDENTIALS')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('rate_limited_code')
                            ->info('The "errorCode" of a 429. Give it the code of the application\'s other rate limits, so a client that maps one maps them all.')
                            ->defaultValue('RATE_LIMITED')
                            ->cannotBeEmpty()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('account')
                    ->info('The account commands: app:user:create, and app:dev:login-link with the target of its link. Each is off by default: an application keeps its own until it turns the bundle\'s on. Needs symfony/console.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('user_class')
                            ->info('The account entity the commands create and look up, written through its own setters.')
                            ->defaultValue(User::class)
                            ->cannotBeEmpty()
                        ->end()
                        ->arrayNode('create_user')
                            ->info('app:user:create: an account from the console, its password asked hidden.')
                            ->canBeEnabled()
                            ->children()
                                ->scalarNode('admin_role')
                                    ->info('The role --admin gives.')
                                    ->defaultValue('ROLE_SUPER_ADMIN')
                                    ->cannotBeEmpty()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('dev_login_link')
                            ->info('app:dev:login-link and the target of its link (Jul6Art\\AuthBundle\\Account\\Dev\\LoginLinkController, routed by the application under when@dev). Registered in the "dev" environment only, whatever this says.')
                            ->canBeEnabled()
                            ->children()
                                ->scalarNode('firewall')
                                    ->info('The firewall whose login_link makes the URL.')
                                    ->defaultValue('main')
                                    ->cannotBeEmpty()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('api')
                    ->info('The API sign-in: password, second factor, cookies, refresh, forgotten password. Off by default; its packages are suggested, not required.')
                    ->canBeEnabled()
                    ->children()
                        ->booleanNode('two_factor_required')
                            ->info('Whether every account owes a second factor. Ignored in the "prod" environment, where it always does.')
                            ->defaultTrue()
                        ->end()
                        ->arrayNode('two_factor_throttling')
                            ->info('The budget of wrong codes of an account, whatever its address: the sign-in\'s second factor, the enrolment, the activation and #[CurrentTotpCode] spend it; a right code clears it.')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('max_attempts')->min(1)->defaultValue(5)->end()
                                ->scalarNode('interval')->cannotBeEmpty()->defaultValue('15 minutes')->end()
                                ->scalarNode('cache_pool')
                                    ->info('The cache pool of the counters. Null: a filesystem pool of the bundle ("auth.two_factor_throttling.cache"). Never an array pool, which forgets at the end of each request.')
                                    ->defaultNull()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('realms')
                            ->info('One realm per application whose accounts sign in: its firewalls, its classes, its name, its e-mails.')
                            ->useAttributeAsKey('name')
                            ->arrayPrototype()
                                ->children()
                                    ->arrayNode('firewalls')
                                        ->info('The firewalls of the realm: its sign-in, its public routes, its API.')
                                        ->isRequired()
                                        ->requiresAtLeastOneElement()
                                        ->scalarPrototype()->cannotBeEmpty()->end()
                                    ->end()
                                    ->scalarNode('user_class')->isRequired()->cannotBeEmpty()->end()
                                    ->scalarNode('login_record_class')->isRequired()->cannotBeEmpty()->end()
                                    ->scalarNode('refresh_token_class')->isRequired()->cannotBeEmpty()->end()
                                    ->scalarNode('reset_password_request_class')->isRequired()->cannotBeEmpty()->end()
                                    ->scalarNode('issuer')
                                        ->info('The name the authenticator app and the e-mails show.')
                                        ->isRequired()
                                        ->cannotBeEmpty()
                                    ->end()
                                    ->arrayNode('mail')
                                        ->isRequired()
                                        ->children()
                                            ->scalarNode('from')->isRequired()->cannotBeEmpty()->end()
                                            ->arrayNode('reset_links')
                                                ->info('The reset screen by language, "{token}" in place of the token: never built from the request\'s host.')
                                                ->isRequired()
                                                ->requiresAtLeastOneElement()
                                                ->useAttributeAsKey('locale')
                                                ->scalarPrototype()->cannotBeEmpty()->end()
                                            ->end()
                                            ->scalarNode('html_template')->defaultValue('@Auth/emails/password_reset.html.twig')->end()
                                            ->scalarNode('text_template')->defaultValue('@Auth/emails/password_reset.txt.twig')->end()
                                            ->scalarNode('subject')->defaultValue('password_reset.subject')->end()
                                            ->scalarNode('translation_domain')->defaultValue('auth_emails')->end()
                                        ->end()
                                    ->end()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end();

        return $treeBuilder;
    }
}
